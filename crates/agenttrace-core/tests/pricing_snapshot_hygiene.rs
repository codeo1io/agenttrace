//! rm-903: the vendored pricing bundle must carry zero wildcard keys —
//! LiteLLM publishes `'*'` glob keys (`bedrock/*/1-month-commitment/…`,
//! 4 of them as of the 2026-10-08 refresh) whose glob semantics our
//! exact-key lookup can never honor, so `scripts/pricing/
//! update-snapshot.sh` skips them at refresh time and this pin holds
//! the line on the bundle itself: any future refresh that re-admits a
//! wildcard row fails here instead of shipping unmatchable dead
//! weight. Concrete-region commitment-tier keys (e.g. `…/1-month-
//! commitment/<model>`) deliberately stay — they are exact-matchable
//! strings and priced rows in their own right.
//!
//! rm-1508 (run 5c144613 cycle 4): the cache-rate census pin. The
//! 2026-10-08 bundle was generated by the pre-fix zero-fill, so every
//! row that publishes no cache rate carries an explicit `0` — the
//! ingest distinction (absent vs published-$0) cannot exist for
//! bundled rows until the next sanctioned refresh
//! (scripts/pricing/update-snapshot.sh now preserves absence; the
//! rm-176 reconcile lane owns the refresh itself). This pin makes the
//! movement conscious: a refresh that introduces genuinely-absent
//! rows flips `absent_*` off zero and must update this pin (and the
//! fallback disclosure expectations) deliberately, not silently.
//!
//! rm-1954 (run ce9309d9 cycle 1, batch "battery-truth hygiene"):
//! cache_rate_census() resolves through the same public lane that
//! PREFERS a machine pricing cache (`$AGENTTRACE_SESSION_CACHE_DIR/
//! pricing.json` or the default user-cache location) over the bundled
//! snapshot — and the catalog initializes once per process, so
//! ambient host cache state would silently re-point this census
//! (assess f4cb5f63 F2). The census arm below therefore runs inside
//! `support::with_isolated_pricing_env` (fresh scratch session cache,
//! scratch HOME, and the AGENTTRACE_PRICING_FILE override cleared),
//! making the pinned counts deterministic battery truth. The wildcard
//! arm reads the bundle FILE directly and needs no guard.

mod support;

#[test]
fn vendored_pricing_bundle_carries_no_wildcard_keys() {
    let raw = include_str!(concat!(
        env!("CARGO_MANIFEST_DIR"),
        "/src/pricing_snapshot.json"
    ));
    let parsed: serde_json::Value =
        serde_json::from_str(raw).expect("vendored pricing snapshot must parse");
    let offenders: Vec<&str> = parsed
        .as_object()
        .expect("pricing snapshot is a JSON object keyed by model name")
        .keys()
        .map(|key| key.as_str())
        .filter(|key| key.contains('*'))
        .collect();
    assert!(
        offenders.is_empty(),
        "vendored pricing snapshot carries wildcard keys the exact-key lookup can never hit \
         (refresh via scripts/pricing/update-snapshot.sh skips '*' keys at the mode filter): \
         {offenders:?}"
    );
}

#[test]
fn vendored_pricing_bundle_cache_rate_census_is_pinned() {
    support::with_isolated_pricing_env(cache_rate_census_body);
}

fn cache_rate_census_body() {
    // rm-1508: classify the bundle through the real ingest — the
    // process catalog of a test binary with no AGENTTRACE_PRICING_FILE
    // is exactly the bundled snapshot plus the vendored SKU rows
    // (rm-1954: guaranteed by the isolation guard wrapping this body,
    // not by host state).
    let census = agenttrace_core::cache_rate_census();
    assert!(
        census.models > 1000,
        "the bundle must still be the full LiteLLM chat catalog (got {})",
        census.models
    );
    assert_eq!(
        census.cache_read_absent, 0,
        "the 2026-10-08 bundle zero-fills: absent cache-read rows can only appear via a \
         sanctioned refresh (rm-176 lane), which must move this pin consciously"
    );
    assert_eq!(
        census.cache_write_absent, 0,
        "the 2026-10-08 bundle zero-fills (upstream even publishes an explicit $0 on the \
         gpt-5.3-codex rows, so the vend row is Some(0.0)): absent rows can only appear \
         via a sanctioned refresh (rm-176 lane), which must move this pin consciously"
    );
    assert_eq!(
        census.cache_read_absent + census.cache_read_zero + census.cache_read_published,
        census.models
    );
    assert_eq!(
        census.cache_write_absent + census.cache_write_zero + census.cache_write_published,
        census.models
    );
}

#[test]
fn vendored_bundle_prices_gemini_4_argon_exactly() {
    support::with_isolated_pricing_env(gemini_4_argon_price_body);
}

fn gemini_4_argon_price_body() {
    // rm-176 (run d5e143bce25e cycle 7): the 2026-10-08 bundle carried
    // ZERO gemini-4* rows while the live source had priced the argon
    // family since 2026-10-19, so every gemini-4 session fell back to
    // the $3/$15 default — a 1.5x overstatement on both axes for the
    // 2e-6/1e-5 rows. Red-first pin for the 2026-10-22 union refresh
    // (scripts/pricing/update-snapshot.sh): hold the exact refreshed
    // rates so a future refresh that loses or corrupts the family goes
    // red here instead of silently re-enabling the fallback.
    // Per-million units (Price is $/Mtok). Isolated like the census
    // arm (rm-1954) — the public lookup lane prefers a machine cache
    // over the bundle.
    assert!(
        agenttrace_core::has_specific_price("gemini/gemini-4-argon"),
        "the gemini first-party argon row must be priced, not defaulted"
    );
    let price = agenttrace_core::lookup_price("gemini/gemini-4-argon");
    // Live rates 2026-10-22: 2e-6 in / 1e-5 out / 1e-7 cache-read per
    // token; no published cache-write rate (the disclosed rm-1508
    // fallback bills it at input x 1.25).
    let eps = 1e-12;
    assert!((price.input - 2.0).abs() < eps, "input {}", price.input);
    assert!((price.output - 10.0).abs() < eps, "output {}", price.output);
    assert!((price.cr.unwrap() - 0.1).abs() < eps, "cr {:?}", price.cr);
    assert!(
        price.cw.is_none(),
        "cw stays unpublished (None), never zero-filled: {:?}",
        price.cw
    );
    let (billed_cw, fallback) = price.cache_write_billed();
    assert!(
        fallback,
        "absent cache-write must bill at the disclosed fallback"
    );
    assert!((billed_cw - 2.5).abs() < eps, "fallback is input x 1.25: {billed_cw}");
    // The reseller-qualified argon rows land with the same refresh:
    // vertex_ai x2 (cyber-permissive at 4e-6/2e-5) and github_copilot
    // (200k context). Same exact-rate discipline on each qualified key.
    for (key, input, output) in [
        ("vertex_ai/gemini-4-argon", 2.0, 10.0),
        ("vertex_ai/gemini-4-argon-cyber-permissive", 4.0, 20.0),
        ("github_copilot/gemini-4-argon", 2.0, 10.0),
    ] {
        let p = agenttrace_core::lookup_price(key);
        assert!((p.input - input).abs() < eps, "{key} input {}", p.input);
        assert!((p.output - output).abs() < eps, "{key} output {}", p.output);
    }
    // The fallback this replaces is default_price() $3/$15 per M —
    // 1.5x the true rates on both axes (pricing.rs default_price).
}
