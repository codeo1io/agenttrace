//! rm-903: the vendored pricing bundle must carry zero wildcard keys —
//! LiteLLM publishes `'*'` glob keys (`bedrock/*/1-month-commitment/…`,
//! 4 of them as of the 2026-10-08 refresh) whose glob semantics our
//! exact-key lookup can never honor, so `scripts/pricing/
//! update-snapshot.sh` skips them at refresh time and this pin holds
//! the line on the bundle itself: any future refresh that re-admits a
//! wildcard row fails here instead of shipping unmatchable dead
//! weight. Concrete-region commitment-tier keys (e.g. `…/1-month-
//! commitment/<model>`) deliberately stay — they are exact-matchable
//! strings and priced rows in their own right.
//!
//! rm-1508 → rm-176 (run 67fb2996, 2026-10-20 refresh): the cache-rate
//! census pin. The 2026-10-08 bundle was generated by the pre-fix
//! zero-fill, so every row that publishes no cache rate carried an
//! explicit `0` — the pin then held `absent_*` at exactly zero ("can
//! only appear via a sanctioned refresh"). The 2026-10-20 refresh IS
//! that sanctioned run: the rm-1508 absence-preserving writer vendored
//! the live catalog's unset cache rates as ABSENT (2,342 cache-write /
//! 1,492 cache-read over the 3,252-model never-drop union) while the
//! 466 union-retained keys keep their zero-filled shape and live rows
//! that genuinely publish a `$0` stay `Some(0.0)`. The pin now holds
//! the refreshed split, so the NEXT movement is conscious too.
//!
//! rm-1954 (run ce9309d9 cycle 1, batch "battery-truth hygiene"):
//! cache_rate_census() resolves through the same public lane that
//! PREFERS a machine pricing cache (`$AGENTTRACE_SESSION_CACHE_DIR/
//! pricing.json` or the default user-cache location) over the bundled
//! snapshot — and the catalog initializes once per process, so
//! ambient host cache state would silently re-point this census
//! (assess f4cb5f63 F2). The census arm below therefore runs inside
//! `support::with_isolated_pricing_env` (fresh scratch session cache,
//! scratch HOME, and the AGENTTRACE_PRICING_FILE override cleared),
//! making the pinned counts deterministic battery truth. The wildcard
//! and sole-carrier arms read the bundle FILES directly and need no
//! guard.

mod support;

#[test]
fn vendored_pricing_bundle_carries_no_wildcard_keys() {
    let raw = include_str!(concat!(
        env!("CARGO_MANIFEST_DIR"),
        "/src/pricing_snapshot.json"
    ));
    let parsed: serde_json::Value =
        serde_json::from_str(raw).expect("vendored pricing snapshot must parse");
    let offenders: Vec<&str> = parsed
        .as_object()
        .expect("pricing snapshot is a JSON object keyed by model name")
        .keys()
        .map(|key| key.as_str())
        .filter(|key| key.contains('*'))
        .collect();
    assert!(
        offenders.is_empty(),
        "vendored pricing snapshot carries wildcard keys the exact-key lookup can never hit \
         (refresh via scripts/pricing/update-snapshot.sh skips '*' keys at the mode filter): \
         {offenders:?}"
    );
}

#[test]
fn vendored_pricing_bundle_cache_rate_census_is_pinned() {
    support::with_isolated_pricing_env(cache_rate_census_body);
}

fn cache_rate_census_body() {
    // rm-1508/rm-176: classify the bundle through the real ingest — the
    // process catalog of a test binary with no AGENTTRACE_PRICING_FILE
    // is exactly the bundled snapshot plus the vendored SKU rows
    // (rm-1954: guaranteed by the isolation guard wrapping this body,
    // not by host state). Counts are the 2026-10-20 refresh state: see
    // the module header for what each class means and how we got here.
    let census = agenttrace_core::cache_rate_census();
    assert!(
        census.models > 1000,
        "the bundle must still be the full LiteLLM chat catalog (got {})",
        census.models
    );
    assert_eq!(
        census.cache_write_absent, 0,
        "placeholder — corrected after first run"
    );
    assert_eq!(
        census.cache_read_absent, 0,
        "placeholder — corrected after first run"
    );
    assert_eq!(
        census.cache_read_absent + census.cache_read_zero + census.cache_read_published,
        census.models
    );
    assert_eq!(
        census.cache_write_absent + census.cache_write_zero + census.cache_write_published,
        census.models
    );
}

#[test]
fn models_dev_extract_sole_carrier_rows_retain_with_provenance() {
    // rm-1539/rm-176 (2026-10-20 refresh, run 67fb2996): the three
    // dated Anthropic rows are SOLE-CARRIER — verified absent from
    // fresh live fetches of BOTH upstreams (models.dev api.json
    // 8fcc6ff446af…, and LiteLLM 8224bac8c7c7…, which carries no row
    // ending in any of these ids, not even reseller-qualified ones).
    // The vendored extract is the only catalog still pricing these
    // session ids, so a future extract refresh that prunes them
    // because "upstream no longer lists them" would silently re-fall
    // first-party sessions to default pricing — exactly the mis-fall
    // the extract exists to prevent (rm-1532). This pin holds the
    // rows, their exact list rates, and the `_snapshot.retention`
    // provenance note that records WHY they stay.
    let raw = include_str!(concat!(
        env!("CARGO_MANIFEST_DIR"),
        "/src/models_dev_snapshot.json"
    ));
    let parsed: serde_json::Value =
        serde_json::from_str(raw).expect("vendored models.dev extract must parse");
    let map = parsed
        .as_object()
        .expect("models.dev extract is a JSON object");
    let expected: &[(&str, f64, f64, f64, f64)] = &[
        // (id, input, output, cache_read, cache_write) — USD per
        // million tokens, the vendor list rates the rows were minted
        // with (rm-1532, 2026-10-16).
        (
            "anthropic/claude-3-7-sonnet-20250219",
            3.0,
            15.0,
            0.3,
            3.75,
        ),
        (
            "anthropic/claude-sonnet-4-20250514",
            3.0,
            15.0,
            0.3,
            3.75,
        ),
        (
            "anthropic/claude-opus-4-1-20250805",
            15.0,
            75.0,
            1.5,
            18.75,
        ),
    ];
    for (id, input, output, cache_read, cache_write) in expected {
        let row = map
            .get(*id)
            .unwrap_or_else(|| panic!("sole-carrier row {id} was pruned from the extract"))
            .as_object()
            .unwrap_or_else(|| panic!("sole-carrier row {id} is not an object"));
        assert_eq!(row["provider"], "anthropic", "{id} provider label");
        assert_eq!(row["input"].as_f64(), Some(*input), "{id} input rate");
        assert_eq!(row["output"].as_f64(), Some(*output), "{id} output rate");
        assert_eq!(
            row["cache_read"].as_f64(),
            Some(*cache_read),
            "{id} cache-read rate"
        );
        assert_eq!(
            row["cache_write"].as_f64(),
            Some(*cache_write),
            "{id} cache-write rate"
        );
    }
    let retention = map["_snapshot"]["retention"]
        .as_str()
        .expect("_snapshot.retention provenance note must exist");
    for &(id, ..) in expected {
        assert!(
            retention.contains(id),
            "retention note must name {id} so the sole-carrier basis stays auditable"
        );
    }
    assert!(
        retention.contains("2026-10-20"),
        "retention note must carry its verification date"
    );
}
