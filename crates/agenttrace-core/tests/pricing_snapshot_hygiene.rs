//! rm-903: the vendored pricing bundle must carry zero wildcard keys —
//! LiteLLM publishes `'*'` glob keys (`bedrock/*/1-month-commitment/…`,
//! 4 of them as of the 2026-10-08 refresh) whose glob semantics our
//! exact-key lookup can never honor, so `scripts/pricing/
//! update-snapshot.sh` skips them at refresh time and this pin holds
//! the line on the bundle itself: any future refresh that re-admits a
//! wildcard row fails here instead of shipping unmatchable dead
//! weight. Concrete-region commitment-tier keys (e.g. `…/1-month-
//! commitment/<model>`) deliberately stay — they are exact-matchable
//! strings and priced rows in their own right.
//!
//! rm-1508 (run 5c144613 cycle 4): the cache-rate census pin. The
//! 2026-10-08 bundle was generated by the pre-fix zero-fill, so every
//! row that publishes no cache rate carried an explicit `0` — the
//! ingest distinction (absent vs published-$0) could not exist for
//! bundled rows. The sanctioned rm-176 refresh LANDED that movement
//! (2026-10-17, run ab7a73576cd1 cycle 5: 3,130 → 2,771 chat models,
//! 2,227 read-absent / 3,345 write-absent catalog rows), so absence
//! is the bundle's designed state from that vintage on. Exact absence
//! totals would redden master on every future sanctioned refresh —
//! the weekly drift workflow ships the refreshed bundle without
//! touching test files — so this pin now holds the vintage-free
//! invariants instead (full catalog, partition, live absence); the
//! conscious-movement tripwire the original zero-pin provided is
//! carried by the refresh machinery's own fail-closed guards (pinned
//! textually in tests/models_dev_extract_contract.rs).

#[test]
fn vendored_pricing_bundle_carries_no_wildcard_keys() {
    let raw = include_str!(concat!(
        env!("CARGO_MANIFEST_DIR"),
        "/src/pricing_snapshot.json"
    ));
    let parsed: serde_json::Value =
        serde_json::from_str(raw).expect("vendored pricing snapshot must parse");
    let offenders: Vec<&str> = parsed
        .as_object()
        .expect("pricing snapshot is a JSON object keyed by model name")
        .keys()
        .map(|key| key.as_str())
        .filter(|key| key.contains('*'))
        .collect();
    assert!(
        offenders.is_empty(),
        "vendored pricing snapshot carries wildcard keys the exact-key lookup can never hit \
         (refresh via scripts/pricing/update-snapshot.sh skips '*' keys at the mode filter): \
         {offenders:?}"
    );
}

#[test]
fn vendored_pricing_bundle_cache_rate_census_is_pinned() {
    // rm-1508/rm-176 (2026-10-17 refresh): classify the bundle through
    // the real ingest — the process catalog of a test binary with no
    // AGENTTRACE_PRICING_FILE is exactly the bundled snapshot plus the
    // vendored SKU rows. The sanctioned 2026-10-17 refresh landed the
    // first absence-preserving bundle, so `absent_*` is deliberately
    // non-zero and bundle-vintage-dependent from this vintage on; the
    // pre-refresh zero-pin is retired with it (see the module header:
    // exact totals would redden master on every future sanctioned
    // refresh, which the weekly drift workflow ships as an auto-PR).
    // Vintage-free invariants: the catalog is full, every row
    // classifies into exactly one class per side, and the ingest
    // distinction rm-1508 built is LIVE in the population.
    let census = agenttrace_core::cache_rate_census();
    assert!(
        census.models > 1000,
        "the bundle must still be the full LiteLLM chat catalog (got {})",
        census.models
    );
    assert!(
        census.cache_read_absent > 0 && census.cache_write_absent > 0,
        "the 2026-10-17 rm-176 refresh preserves absence — both sides must \
         classify live absent rows (got {census:?}); zero would mean the \
         zero-fill regressed or the bundle predates the refresh"
    );
    assert_eq!(
        census.cache_read_absent + census.cache_read_zero + census.cache_read_published,
        census.models
    );
    assert_eq!(
        census.cache_write_absent + census.cache_write_zero + census.cache_write_published,
        census.models
    );
}
