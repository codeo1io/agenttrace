//! rm-903: the vendored pricing bundle must carry zero wildcard keys —
//! LiteLLM publishes `'*'` glob keys (`bedrock/*/1-month-commitment/…`,
//! 4 of them as of the 2026-10-08 refresh) whose glob semantics our
//! exact-key lookup can never honor, so `scripts/pricing/
//! update-snapshot.sh` skips them at refresh time and this pin holds
//! the line on the bundle itself: any future refresh that re-admits a
//! wildcard row fails here instead of shipping unmatchable dead
//! weight. Concrete-region commitment-tier keys (e.g. `…/1-month-
//! commitment/<model>`) deliberately stay — they are exact-matchable
//! strings and priced rows in their own right.
//!
//! rm-1508 (run 5c144613 cycle 4): the cache-rate census pin. The
//! 2026-10-08 bundle was generated by the pre-fix zero-fill, so every
//! row that publishes no cache rate carries an explicit `0` — the
//! ingest distinction (absent vs published-$0) cannot exist for
//! bundled rows until the next sanctioned refresh
//! (scripts/pricing/update-snapshot.sh now preserves absence; the
//! rm-176 reconcile lane owns the refresh itself). This pin makes the
//! movement conscious: a refresh that introduces genuinely-absent
//! rows flips `absent_*` off zero and must update this pin (and the
//! fallback disclosure expectations) deliberately, not silently.

#[test]
fn vendored_pricing_bundle_carries_no_wildcard_keys() {
    let raw = include_str!(concat!(
        env!("CARGO_MANIFEST_DIR"),
        "/src/pricing_snapshot.json"
    ));
    let parsed: serde_json::Value =
        serde_json::from_str(raw).expect("vendored pricing snapshot must parse");
    let offenders: Vec<&str> = parsed
        .as_object()
        .expect("pricing snapshot is a JSON object keyed by model name")
        .keys()
        .map(|key| key.as_str())
        .filter(|key| key.contains('*'))
        .collect();
    assert!(
        offenders.is_empty(),
        "vendored pricing snapshot carries wildcard keys the exact-key lookup can never hit \
         (refresh via scripts/pricing/update-snapshot.sh skips '*' keys at the mode filter): \
         {offenders:?}"
    );
}

#[test]
fn vendored_pricing_bundle_cache_rate_census_is_pinned() {
    // rm-1508: classify the bundle through the real ingest — the
    // process catalog of a test binary with no AGENTTRACE_PRICING_FILE
    // is exactly the bundled snapshot plus the vendored SKU rows.
    let census = agenttrace_core::cache_rate_census();
    assert!(
        census.models > 1000,
        "the bundle must still be the full LiteLLM chat catalog (got {})",
        census.models
    );
    assert_eq!(
        census.cache_read_absent, 0,
        "the 2026-10-08 bundle zero-fills: absent cache-read rows can only appear via a \
         sanctioned refresh (rm-176 lane), which must move this pin consciously"
    );
    assert_eq!(
        census.cache_write_absent, 0,
        "the 2026-10-08 bundle zero-fills (upstream even publishes an explicit $0 on the \
         gpt-5.3-codex rows, so the vend row is Some(0.0)): absent rows can only appear \
         via a sanctioned refresh (rm-176 lane), which must move this pin consciously"
    );
    assert_eq!(
        census.cache_read_absent + census.cache_read_zero + census.cache_read_published,
        census.models
    );
    assert_eq!(
        census.cache_write_absent + census.cache_write_zero + census.cache_write_published,
        census.models
    );
}
