#!/usr/bin/env bash
set -euo pipefail

# rm-1984: bound the in-tree docs/stewardship growth (first landing
# 2026-10-18, run bd3301ff member 3, batch "merge-safety & docs-truth
# hygiene" — selection e229cc98 / stewardship ddb09160). Stewardship
# records are append-only evidence, but the inline directory is not a
# landfill: the RETENTION BOUND is the MAX_INLINE_CYCLES most-recent
# maintenance cycles inline; older records move to
# docs/archive/stewardship/ via `git mv` (flat, original basenames —
# the date-prefixed names are globally unique) plus this script's
# --regen-index, and docs/archive/stewardship/INDEX.md carries the
# old-inline-path -> archived-path mapping so ROADMAP banners, review
# and research docs can cite either form.
#
# A "cycle" key is (date, cycle-number) parsed from the filename:
# `2026-10-15-cycle3-compound-record-run….md` -> (2026-10-15, 3); the
# pre-2026-09-14 spelling `2026-09-02-cycle-2-…` normalizes the same
# way; a file with no cycle token (e.g. `2026-09-02-final-validation-
# record.md`) groups as cycle 0 of its date, so it archives with its
# era instead of escaping the bound.
#
# Modes:
#   (default)      gate — fails when docs/stewardship/ holds more than
#                  MAX_INLINE_CYCLES distinct cycle keys (listing the
#                  excess), and fails when the archive's INDEX.md is
#                  stale (run --regen-index after every archival move).
#   --regen-index  deterministically rebuild
#                  docs/archive/stewardship/INDEX.md from the archive's
#                  current contents (no timestamps — byte-stable for a
#                  fixed archive set).

MAX_INLINE_CYCLES=12

repo_root="$(git rev-parse --show-toplevel)"
cd "$repo_root"

inline_dir="docs/stewardship"
archive_dir="docs/archive/stewardship"
index_path="$archive_dir/INDEX.md"

fail() {
	echo "check-stewardship-retention: $*" >&2
	exit 1
}

# cycle_key <filename> -> "YYYY-MM-DD <num>" (cycle 0 when no token).
cycle_key() {
	awk '
		{
			if (match($0, /^[0-9]{4}-[0-9]{2}-[0-9]{2}-cycle[-_]?[0-9]+/)) {
				head = substr($0, RSTART, RLENGTH)
				sub(/-cycle[-_]?/, " ", head)
				print head
			} else if (match($0, /^[0-9]{4}-[0-9]{2}-[0-9]{2}-/)) {
				print substr($0, RSTART, RLENGTH - 1) " 0"
			} else {
				print "9999-99-99 0"
			}
			exit
		}
	' <<<"$1"
}

# The keys that must stay inline: the newest MAX_INLINE_CYCLES distinct
# (date, cycle) keys across the inline directory, one "date_num" per line.
inline_keep_keys() {
	local f
	{
		shopt -s nullglob
		for f in "$inline_dir"/*; do
			cycle_key "$(basename "$f")"
		done
	} | sort -u -k1,1r -k2,2nr | head -n "$MAX_INLINE_CYCLES" | awk '{ print $1 "_" $2 }'
}

# The archive index body — a pure function of the archive's contents
# (deterministic: no timestamps), so the gate can diff it against the
# committed INDEX.md.
index_content() {
	echo "# Stewardship record archive — index"
	echo
	echo "Generated by \`scripts/ci/check-stewardship-retention.sh --regen-index\`"
	echo "(rm-1984 retention bound: the $MAX_INLINE_CYCLES most-recent maintenance"
	echo "cycles stay inline under \`docs/stewardship/\`; older records live here,"
	echo "flat, with their original basenames — the \`YYYY-MM-DD\` prefixes keep"
	echo "them unique). Cite either the archived path or the original inline"
	echo "path; this index is the mapping. Regenerate after every archival move."
	echo
	echo "| archived path | original inline path | cycle | record |"
	echo "| --- | --- | --- | --- |"
	local f base key title
	shopt -s nullglob
	for f in "$archive_dir"/*; do
		[ -f "$f" ] || continue
		base="$(basename "$f")"
		# Never index the index itself (it lives in the archive dir but
		# is not a record).
		[ "$base" = "INDEX.md" ] && continue
		key="$(cycle_key "$base")"
		title="$(awk '/^#{1,2} / { sub(/^#+ +/, ""); gsub(/\|/, "\\|"); print; exit }' "$f")"
		echo "| $archive_dir/$base | $inline_dir/$base | $key | ${title:--} |"
	done | sort -t' ' -k1,1
}

[ $# -le 1 ] || fail "usage: $0 [--regen-index]"

if [ "${1:-}" = "--regen-index" ]; then
	mkdir -p "$archive_dir"
	# Write to a scratch file and move into place: redirecting straight
	# into $index_path would create the file BEFORE the listing glob runs,
	# and the index would list itself (a self-row survived the first regen
	# this way — caught while landing, 2026-10-18).
	scratch="$(mktemp "${TMPDIR:-/tmp}/at-stewardship-index.XXXXXX")"
	index_content >"$scratch"
	mv "$scratch" "$index_path"
	echo "check-stewardship-retention: regenerated $index_path"
	exit 0
fi

# --- Gate arm 1: the inline bound ------------------------------------------
shopt -s nullglob
inline_files=("$inline_dir"/*)
if [ "${#inline_files[@]}" -eq 0 ]; then
	fail "$inline_dir is empty or missing — the retention bound assumes the newest cycles stay inline"
fi

keep_map="$(inline_keep_keys)"
key_count="$(wc -l <<<"$keep_map")"

violations="$(mktemp "${TMPDIR:-/tmp}/at-stewardship-retention.XXXXXX")"
expected_index="$(mktemp "${TMPDIR:-/tmp}/at-stewardship-index.XXXXXX")"
cleanup() { rm -f "$violations" "$expected_index"; }
trap cleanup EXIT

for f in "${inline_files[@]}"; do
	base="$(basename "$f")"
	key="$(cycle_key "$base")"
	if ! grep -qx "${key%% *}_${key##* }" <<<"$keep_map"; then
		echo "  $base  (cycle $key) is past the inline bound" >>"$violations"
	fi
done

if [ -s "$violations" ]; then
	{
		echo "check-stewardship-retention: docs/stewardship/ holds records past the"
		echo "retention bound ($MAX_INLINE_CYCLES most-recent cycles inline):"
		cat "$violations"
		echo "Archive them: git mv docs/stewardship/<file> docs/archive/stewardship/"
		echo "then scripts/ci/check-stewardship-retention.sh --regen-index"
	} >&2
	fail "retention bound exceeded"
fi

# --- Gate arm 2: the archive index is fresh --------------------------------
if [ -d "$archive_dir" ] || [ -f "$index_path" ]; then
	index_content >"$expected_index"
	if ! cmp -s "$expected_index" "$index_path"; then
		fail "docs/archive/stewardship/INDEX.md is stale — run scripts/ci/check-stewardship-retention.sh --regen-index"
	fi
fi

echo "check-stewardship-retention: ok ($key_count inline cycle(s) within the $MAX_INLINE_CYCLES bound; archive index fresh)"
